// Run from mobile: node scripts/test-menu-permissions.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/lib/permissions.ts'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const compiled = { exports: {} };
new Function('exports', 'module', code)(compiled.exports, compiled);
const { canView, canCreateInquiry, getVisibleMenuItems } = compiled.exports;
const employee = permissions => ({ role: 'employee', access_level: 'employee', permissions });
const screens = user => getVisibleMenuItems(user).map(item => item.screen);
const warehouse = employee(['equipment_manage', 'tasks_view', 'tasks_create', 'calendar_view']);
assert.ok(screens(warehouse).includes('Events'));
assert.ok(screens(warehouse).includes('Calendar'));
assert.ok(screens(warehouse).includes('Tasks'));
assert.ok(!screens(warehouse).includes('Inquiries'), 'Task access must not expose inquiries');
assert.ok(!screens(warehouse).includes('Messages'));
assert.equal(canCreateInquiry(warehouse), false, 'Task creation alone must not show calendar inquiry action');
const chatOnly = employee(['chat_view']);
assert.equal(canView(chatOnly, 'chat'), true);
assert.equal(canView(chatOnly, 'messages'), false);
assert.ok(screens(chatOnly).includes('Messages'));
assert.ok(!screens(chatOnly).includes('Inbox'));
const mailOnly = employee(['messages_view']);
assert.ok(!screens(mailOnly).includes('Messages'));
assert.ok(screens(mailOnly).includes('Inbox'));
assert.equal(canCreateInquiry(employee(['inquiries_view'])), false);
assert.equal(canCreateInquiry(employee(['inquiries_view', 'tasks_create'])), true);
assert.equal(canCreateInquiry(employee(['inquiries_manage'])), true);
assert.equal(canCreateInquiry(employee(['inquiries_view', 'inquiries_manage_all'])), true);
assert.ok(screens(employee(['inquiries_view'])).includes('Inquiries'));
assert.equal(canView(employee([]), 'chat'), false);
assert.equal(canCreateInquiry(null), false);
assert.equal(canCreateInquiry({ ...employee([]), role: 'admin' }), true);
console.log('20 mobile menu/access checks passed.');
