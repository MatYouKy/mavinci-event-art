const fs=require('node:fs'), assert=require('node:assert/strict');
const ts=require('typescript');
const src=fs.readFileSync('src/lib/CRM/equipment/kitInventory.ts','utf8');
const mod={exports:{}}; new Function('exports','require','module',ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText)(mod.exports,require,mod);
const {checkKitInventory,kitEventLimits,usableEquipmentStock}=mod.exports;
const items=[{equipment_id:'p',cable_id:null,quantity:2}], kit={id:'k',quantity:4,equipment_kit_items:items};
const equipment=[{id:'p',name:'Portman',total_quantity:8,equipment_units:Array.from({length:8},()=>({status:'available'}))}];
assert.equal(checkKitInventory('k',4,items,[kit],equipment,[]).shortages.length,0);
assert.equal(checkKitInventory('k',5,items,[kit],equipment,[]).maxQuantity,4);
assert.equal(checkKitInventory(null,1,items,[kit],equipment,[]).maxQuantity,0);
assert.equal(checkKitInventory('k',3,items,[kit,{...kit,id:'k2',quantity:1}],equipment,[]).maxQuantity,3);
assert.equal(checkKitInventory('k',4,[...items,...items],[kit],equipment,[]).maxQuantity,2);
equipment[0].equipment_units[0].status='damaged'; assert.equal(usableEquipmentStock(equipment[0]),7);
assert.equal(checkKitInventory('k',4,items,[kit],equipment,[]).maxQuantity,3);
assert.deepEqual(kitEventLimits(kit,{'item-p':{available_in_term:7,used_by_this_event:8}},4,0),{maxSet:3,maxAdd:0});
assert.deepEqual(kitEventLimits(kit,{'item-p':{available_in_term:7,used_by_this_event:2}},1,0),{maxSet:3,maxAdd:2});
assert.deepEqual(kitEventLimits(kit,{'item-p':{available_in_term:20,used_by_this_event:0}},0,1),{maxSet:3,maxAdd:3});
assert.deepEqual(kitEventLimits(kit,{'item-p':{available_in_term:8,used_by_this_event:4}},1,0),{maxSet:3,maxAdd:2});
assert.equal(kitEventLimits(kit,{},0,0).maxSet,0);
assert.equal(usableEquipmentStock({id:'x',name:'x',total_quantity:10,equipment_units:[{status:'damaged'}]}),0);
assert.equal(usableEquipmentStock({id:'x',name:'x',total_quantity:10,equipment_units:[]}),10);
assert.throws(()=>checkKitInventory(null,1.5,items,[],equipment,[]));
console.log('PASS 14 inventory and event-limit scenarios');
